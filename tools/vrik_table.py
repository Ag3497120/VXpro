#!/usr/bin/env python3
# vrik_table.py: shims/vrik_table.h - V's skeleton for the native VR arms (shims/vrik.m), from the game's own files
# (rdscan -x + cr2w.py): the player rigs' bones (woman_base / man_base deformation rigs: names, parents from their A
# pose (MS = parent MS * LS), bind positions), each bone's arm segment (its nearest ancestor among LeftArm / LeftForeArm /
# LeftHand / RightArm / RightForeArm / RightHand), and the bone lists of the meshes with forearm bones (a skinned draw's
# bone i is its mesh's boneNames[i]; the draw's mesh is told on the headset from the joints its bones agree on).
#   vrik_table.py WOMAN.rig.bin MAN.rig.bin lists.json OUT.h
import sys, json, numpy as np
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from cr2w import CR2W

def qs(t):
    T = t['Translation']; R = t['Rotation']
    x, y, z, w = (R.get(k, 0.0) for k in ('i', 'j', 'k', 'r'))
    M = np.array([[1-2*(y*y+z*z), 2*(x*y-z*w), 2*(x*z+y*w)], [2*(x*y+z*w), 1-2*(x*x+z*z), 2*(y*z-x*w)], [2*(x*z-y*w), 2*(y*z+x*w), 1-2*(x*x+y*y)]])
    return M, np.array([T.get('X', 0.0), T.get('Y', 0.0), T.get('Z', 0.0)])

def rig(path):
    c = CR2W(open(path, 'rb').read()); cls, off, size = c.exports[0]; P = {}
    for n, t, a, b in c.props(off, off + size): P[n] = c.value(t, a, b)
    names = P['boneNames']; LS = [qs(t) for t in P['aPoseLS']]; MS = [qs(t) for t in P['aPoseMS']]
    par = {}
    for i, n in enumerate(names):
        best = (1e9, -1)
        for p in range(len(names)):
            if p == i: continue
            e = np.linalg.norm(MS[p][0] @ LS[i][1] + MS[p][1] - MS[i][1]) + np.linalg.norm(MS[p][0] @ LS[i][0] - MS[i][0])
            if e < best[0]: best = (e, p)
        par[n] = names[best[1]] if best[0] < 1e-3 else None
    return {n: MS[i][1] for i, n in enumerate(names)}, par

SEG = {'LeftArm': 1, 'LeftForeArm': 2, 'LeftHand': 3, 'l_Wrist_2_JNT': 3, 'RightArm': 4, 'RightForeArm': 5, 'RightHand': 6, 'r_Wrist_2_JNT': 6}
def segment(n, par):
    k = n
    for _ in range(64):
        if k in SEG: return SEG[k]
        k = par.get(k)
        if k is None: return 0
    return 0

def list_par(n, pos, par):
    if segment(n, par) <= 0 or any(k in n for k in ('_mscl_JNT', '_out_JNT', '_CRV_')): return -1
    p = par.get(n)
    if p in pos: return pos[p]
    if n == 'LeftForeArm': return pos.get('l_SHL_0_JNT', -1)
    if n == 'RightForeArm': return pos.get('r_SHL_0_JNT', -1)
    if n == 'l_SHL_0_JNT': return pos.get('LeftShoulder', -1)
    if n == 'r_SHL_0_JNT': return pos.get('RightShoulder', -1)
    return -1

def main():
    wpos, wpar = rig(sys.argv[1]); mpos, mpar = rig(sys.argv[2])
    for p in (wpos, mpos):
        if 'LeftArm' in p: p['l_SHL_0_JNT'] = p['LeftArm']
        if 'RightArm' in p: p['r_SHL_0_JNT'] = p['RightArm']
    lists = [l for l, cnt, ex in json.load(open(sys.argv[3])) if len(l) <= 400]
    names = sorted(set(n for l in lists for n in l) | set(wpos) | set(mpos))
    idx = {n: i for i, n in enumerate(names)}
    par = dict(mpar); par.update(wpar)
    o = ['// generated by tools/vrik_table.py from the game\'s rigs and meshes - do not edit', '#pragma once', '#include <stdint.h>',
         'enum { VRIK_NNAMES = %d, VRIK_NLISTS = %d };' % (len(names), len(lists))]
    o.append('static const char *const vrik_names[VRIK_NNAMES] = {' + ','.join('"%s"' % n for n in names) + '};')
    o.append('// per name: arm segment (0 none, 1-3 left upper / fore / hand, 4-6 right), parent (-1: none or not in the rigs)')
    o.append('static const int8_t vrik_seg[VRIK_NNAMES] = {' + ','.join(str(segment(n, par)) for n in names) + '};')
    o.append('static const int16_t vrik_parent[VRIK_NNAMES] = {' + ','.join(str(idx[par[n]]) if par.get(n) in idx else '-1' for n in names) + '};')
    def posrow(tab):
        return ','.join('%.5ff,%.5ff,%.5ff' % tuple(tab[n]) if n in tab else 'NAN,NAN,NAN' for n in names)
    o.append('// bind positions (model space, metres, Z up): [0] woman_base, [1] man_base')
    o.append('static const float vrik_bind[2][VRIK_NNAMES * 3] = {{' + posrow(wpos) + '},{' + posrow(mpos) + '}};')
    offs = [0]; flat = []
    for l in lists: flat += [idx[n] for n in l]; offs.append(len(flat))
    o.append('static const uint32_t vrik_list_off[VRIK_NLISTS + 1] = {' + ','.join(map(str, offs)) + '};')
    o.append('static const uint16_t vrik_list[%d] = {' % len(flat) + ','.join(map(str, flat)) + '};')
    lp = []
    for l in lists:
        pos = {n: i for i, n in enumerate(l)}
        lp += [list_par(n, pos, par) for n in l]
    o.append('// per list entry: the parent bone\'s place in the same list (-1: none)')
    o.append('static const int16_t vrik_list_par[%d] = {' % len(lp) + ','.join(map(str, lp)) + '};')
    for k in SEG: o.append('#define VRIK_%s %d' % (k.upper(), idx[k]))
    for k in ('l_SHL_0_JNT', 'r_SHL_0_JNT', 'LeftHandMiddle1', 'LeftHandIndex1', 'LeftHandPinky1', 'RightHandMiddle1', 'RightHandIndex1', 'RightHandPinky1'):
        o.append('#define VRIK_%s %d' % (k.upper(), idx[k]))
    open(sys.argv[4], 'w').write('\n'.join(o) + '\n')
    print('names', len(names), 'lists', len(lists), 'entries', len(flat))

if __name__ == '__main__': main()
